        let book = session.add_chapter(&book.id, "One", None).unwrap();
        let a = book.spine[0].id.clone();
        let b = book.spine[1].id.clone();

        for bad in [
            vec![a.clone()],                         // too short
            vec![a.clone(), b.clone(), a.clone()],   // too long
            vec![a.clone(), "spine-404".to_owned()], // unknown id
            vec![a.clone(), a.clone()],              // duplicate
        ] {
            let err = session.reorder_spine(&book.id, &bad).unwrap_err();
            assert!(
                matches!(err, CoreError::MalformedPackage { .. }),
                "expected MalformedPackage for {bad:?}"
            );
        }
