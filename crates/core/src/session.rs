    /// Consistency invariants (domain-model.md): every spine resource and
    /// nav target resolves in the manifest; manifest ids/paths are unique.
    fn assert_consistent(book: &Book) {
        for item in &book.spine {
            assert!(
                book.resources.iter().any(|r| r.id == item.resource),
                "spine item {:?} dangles",
                item.id
            );
        }
        fn check_nav(nav: &[NavPoint], resources: &[Resource]) {
            for point in nav {
                if let Some(href) = &point.href {
                    let path = strip_fragment(href);
                    assert!(
                        resources.iter().any(|r| r.path == path),
                        "nav entry {:?} dangles: {href}",
                        point.label
                    );
                }
                check_nav(&point.children, resources);
            }
        }
        check_nav(&book.nav, &book.resources);
        let mut ids = std::collections::HashSet::new();
        let mut paths = std::collections::HashSet::new();
        for r in &book.resources {
            assert!(ids.insert(&r.id), "duplicate manifest id {:?}", r.id);
            assert!(
                paths.insert(&r.path),
                "duplicate manifest path {:?}",
                r.path
            );
        }
    }

