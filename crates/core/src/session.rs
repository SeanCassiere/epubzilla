    #[test]
    fn validate_passes_a_clean_book_and_catches_breakage() {
        let mut session = Session::new();
        let book = session.create_book(sample_metadata());
        let book = session.add_chapter(&book.id, "One", None).unwrap();
        assert!(session.validate(&book.id).unwrap().is_empty());

        // Missing title.
        let mut metadata = sample_metadata();
        metadata.title = String::new();
        session.update_metadata(&book.id, metadata).unwrap();
        let issues = session.validate(&book.id).unwrap();
        assert!(issues
            .iter()
            .any(|i| i.severity == Severity::Error && i.message.contains("dc:title")));
        session
            .update_metadata(&book.id, sample_metadata())
            .unwrap();

        // Dangling spine ref (invariant broken behind the API's back).
        let open = session.books.get_mut(&book.id).unwrap();
        open.book.spine.push(SpineItem {
            id: "spine-bad".into(),
            resource: "ghost".into(),
            linear: true,
        });
        let issues = session.validate(&book.id).unwrap();
        assert!(issues.iter().any(|i| i.message.contains("ghost")));
        let open = session.books.get_mut(&book.id).unwrap();
        open.book.spine.pop();

        // Malformed XHTML bytes.
        let path = open
            .book
            .resources
            .iter()
            .find(|r| r.id == open.book.spine[1].resource)
            .unwrap()
            .path
            .clone();
        let good = open
            .overlay
            .insert(path.clone(), b"<html><p>oops</html>".to_vec());
        let issues = session.validate(&book.id).unwrap();
        assert!(issues
            .iter()
            .any(|i| i.message.contains("not well-formed XML")));
        let open = session.books.get_mut(&book.id).unwrap();
        open.overlay.insert(path.clone(), good.unwrap());

        // Missing resource bytes.
        session
            .books
            .get_mut(&book.id)
            .unwrap()
            .overlay
            .remove(&path);
        let issues = session.validate(&book.id).unwrap();
        assert!(issues.iter().any(|i| i.message.contains("no bytes")));

        // Dangling nav target.
        let open = session.books.get_mut(&book.id).unwrap();
        open.book.nav.push(NavPoint {
            label: "Gone".into(),
            href: Some("OEBPS/gone.xhtml".into()),
            children: Vec::new(),
        });
        let issues = session.validate(&book.id).unwrap();
        assert!(issues
            .iter()
            .any(|i| i.message.contains("not in the manifest")));

        // Duplicate manifest ids.
        let open = session.books.get_mut(&book.id).unwrap();
        let dup = open.book.resources[0].clone();
        open.book.resources.push(dup);
        let issues = session.validate(&book.id).unwrap();
        assert!(issues
            .iter()
            .any(|i| i.message.contains("duplicate manifest id")));
    }

    #[test]
    fn full_mutation_lifecycle_saves_and_reopens_clean() {
        let mut session = Session::new();
        let book = session.create_book(sample_metadata());
        let book_id = book.id.clone();

        // Add three chapters, write Markdown into each.
        let mut chapter_resources = Vec::new();
        for title in ["Ünó", "Dos ✓", "Trés"] {
            let book = session.add_chapter(&book_id, title, None).unwrap();
            chapter_resources.push(book.spine.last().unwrap().resource.clone());
        }
        for (n, resource) in chapter_resources.iter().enumerate() {
            let md = format!("# Chapter {n}\n\nBödy of chapter {n} with *émphasis* ✓.\n");
            session
                .write_chapter(&book_id, resource, md_chapter(resource, &md))
                .unwrap();
        }

        // Reorder: titlepage, Trés, Ünó, Dos ✓.
        let book = session.get_book(&book_id).unwrap();
        let order: Vec<SpineItemId> = vec![
            book.spine[0].id.clone(),
            book.spine[3].id.clone(),
            book.spine[1].id.clone(),
            book.spine[2].id.clone(),
        ];
        session.reorder_spine(&book_id, &order).unwrap();

        // Remove "Dos ✓" (now last).
        let book = session.get_book(&book_id).unwrap();
        let last = book.spine.last().unwrap().id.clone();
        let book = session.remove_chapter(&book_id, &last).unwrap();
        assert_consistent(&book);
        assert!(session.validate(&book_id).unwrap().is_empty());

        // Save, reopen, assert everything survived.
        let path = temp_path("lifecycle.epub");
        session
            .save_book(&book_id, Some(path.to_string_lossy().into_owned()))
            .unwrap();
        let reopened = session.open_book(&path).unwrap();
        assert_consistent(&reopened);
        assert!(!reopened.dirty);
        assert_eq!(reopened.spine.len(), 3);
        let labels: Vec<&str> = reopened.nav.iter().map(|p| p.label.as_str()).collect();
        assert_eq!(labels, ["Nëw “Bøok” ✓", "Trés", "Ünó"]);
        // Spine order: titlepage, Trés (chapter 2), Ünó (chapter 0).
        let spine_paths: Vec<&str> = reopened.spine[1..]
            .iter()
            .map(|s| {
                reopened
                    .resources
                    .iter()
                    .find(|r| r.id == s.resource)
                    .unwrap()
                    .path
                    .as_str()
            })
            .collect();
        let nav_paths: Vec<&str> = reopened.nav[1..]
            .iter()
            .map(|p| p.href.as_deref().unwrap())
            .collect();
        assert_eq!(spine_paths, nav_paths);

        // Chapter content round-trips through the saved file.
        let resource = reopened.spine[2].resource.clone();
        let back = session
            .read_chapter(&reopened.id, &resource, ContentFormat::Markdown)
            .unwrap();
        assert_eq!(back.format, ContentFormat::Markdown);
        assert_eq!(
            back.content,
            "# Chapter 0\n\nBödy of chapter 0 with *émphasis* ✓.\n"
        );

        // The saved file validates with zero findings.
        assert!(session.validate(&reopened.id).unwrap().is_empty());
    }

